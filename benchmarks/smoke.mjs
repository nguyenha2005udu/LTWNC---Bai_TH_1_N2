import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.route('http://localhost:3001/assignments', route => route.fulfill({ json: [] }))
await page.goto('http://127.0.0.1:5173')
await page.getByRole('button', { name: 'Tạo 10.000 bài tập mẫu' }).click()
assert.ok(await page.locator('article').count() < 20)
const second = page.locator('article').nth(1)
const title = await second.locator('h3').textContent()
await second.getByRole('button', { name: 'Ghim', exact: true }).click()
assert.equal(await page.locator('article h3').first().textContent(), title)
await page.getByLabel('Tìm kiếm').fill('React')
await page.waitForTimeout(350)
assert.ok((await page.locator('article .subject').allTextContents()).every(s => s === 'React'))
await page.evaluate(() => { globalThis.__cardRenderCount = 0 })
await page.getByRole('button', { name: 'Chủ đề: Sáng' }).click()
assert.equal(await page.evaluate(() => globalThis.__cardRenderCount), 0)
await page.getByRole('button', { name: 'Thống kê', exact: true }).click()
await page.getByRole('heading', { name: 'Thống kê' }).waitFor()
assert.ok((await page.locator('main').innerText()).includes('Đã xong: 2500'))
await page.getByRole('button', { name: 'Danh sách', exact: true }).click()
await page.screenshot({ path: 'evidence/app.png' })
assert.deepEqual(errors, [])
console.log('Browser smoke passed: stress, pin ordering, search, theme isolation, lazy statistics.')
await browser.close()
